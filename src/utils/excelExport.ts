// Helper to autofit column widths based on contents
function setColumnWidths(ws: XLSX.WorkSheet, data: any[]) {
  if (!data || data.length === 0) return;
  const colKeys = Object.keys(data[0] || {});
  const colWidths = colKeys.map(key => {
    let maxLen = key.length;
    data.forEach(row => {
      const val = row[key];
      if (val !== undefined && val !== null) {
        maxLen = Math.max(maxLen, String(val).length);
      }
    });
    return { wch: Math.min(Math.max(maxLen + 3, 12), 50) };
  });
  ws['!cols'] = colWidths;
}

// 1. Consolidated Master Workbook Export (9 Worksheets)
export function exportConsolidatedWorkbook(
  data: {
    organization: Organization;
    projects: Project[];
    beneficiaries: Beneficiary[];
    staff: StaffMember[];
    donations: Donation[];
    expenses: Expense[];
    events: EventItem[];
    inventory: InventoryItem[];
    tasks: TaskItem[];
  },
  userRole: UserRole = 'Administrator'
) {
  const wb = XLSX.utils.book_new();

  // Sheet 1: Dashboard Summary
  const totalDonations = data.donations.reduce((sum, d) => sum + (d.status === 'Verified' ? d.amount : 0), 0);
  const totalExpenses = data.expenses.reduce((sum, e) => sum + (e.status === 'Approved' ? e.amount : 0), 0);
  const availableFunds = totalDonations - totalExpenses;
  const activeProjects = data.projects.filter(p => p.status === 'Active').length;
  const totalBeneficiaries = data.beneficiaries.length;
  const totalStaff = data.staff.filter(s => s.status === 'Active').length;

  const summarySheetData = [
    { Indicator: 'Organization Name', Value: data.organization.name },
    { Indicator: 'Legal Registration #', Value: data.organization.registrationNumber },
    { Indicator: 'Report Generated Date', Value: new Date().toLocaleDateString() },
    { Indicator: 'Report Generated By Role', Value: userRole },
    { Indicator: '---', Value: '---' },
    { Indicator: 'Total Active Projects', Value: activeProjects },
    { Indicator: 'Total Projects In Registry', Value: data.projects.length },
    { Indicator: 'Total Registered Beneficiaries', Value: totalBeneficiaries },
    { Indicator: 'Active Staff & Volunteers', Value: totalStaff },
    { Indicator: '---', Value: '---' },
    { Indicator: 'Total Verified Donations Received (₹)', Value: totalDonations },
    { Indicator: 'Total Approved Expenses Incurred (₹)', Value: totalExpenses },
    { Indicator: 'Net Available Reserve Funds (₹)', Value: availableFunds },
    { Indicator: '---', Value: '---' },
    { Indicator: 'Total Community Events Conducted', Value: data.events.filter(e => e.status === 'Completed').length },
    { Indicator: 'Total Low Stock Inventory Alerts', Value: data.inventory.filter(i => i.status === 'Low Stock').length },
    { Indicator: 'Pending Action Tasks', Value: data.tasks.filter(t => t.status !== 'Completed').length }
  ];
  const wsSummary = XLSX.utils.json_to_sheet(summarySheetData);
  setColumnWidths(wsSummary, summarySheetData);
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Dashboard Summary');

  // Sheet 2: Projects
  const projectsData = data.projects.map(p => ({
    'Project ID': p.id,
    'Project Name': p.name,
    'Category': p.category,
    'Location': p.location,
    'Manager': p.manager,
    'Budget (₹)': p.budget,
    'Spent (₹)': p.spent,
    'Remaining (₹)': p.budget - p.spent,
    'Utilization %': p.budget > 0 ? `${((p.spent / p.budget) * 100).toFixed(1)}%` : '0%',
    'Start Date': p.startDate,
    'End Date': p.endDate,
    'Status': p.status,
    'Beneficiaries Reached': p.beneficiariesCount,
    'Donor Partners': p.donorPartners.join(', ')
  }));
  const wsProjects = XLSX.utils.json_to_sheet(projectsData);
  setColumnWidths(wsProjects, projectsData);
  XLSX.utils.book_append_sheet(wb, wsProjects, 'Projects');

  // Sheet 3: Beneficiaries (Privacy-safe masking for non-admin)
  const isPrivacyMasked = userRole === 'Staff';
  const beneficiariesData = data.beneficiaries.map(b => ({
    'Beneficiary ID': b.id,
    'Full Name': b.name,
    'Age': b.age,
    'Gender': b.gender,
    'Contact Phone': isPrivacyMasked ? '***-***-' + b.contact.slice(-4) : b.contact,
    'Location': b.location,
    'Category': b.category,
    'Assigned Project': b.assignedProject,
    'Registration Date': b.registrationDate,
    'Status': b.status,
    'Services Received': b.servicesReceived.join('; ')
  }));
  const wsBeneficiaries = XLSX.utils.json_to_sheet(beneficiariesData);
  setColumnWidths(wsBeneficiaries, beneficiariesData);
  XLSX.utils.book_append_sheet(wb, wsBeneficiaries, 'Beneficiaries');

  // Sheet 4: Staff & Volunteers
  const staffData = data.staff.map(s => ({
    'ID': s.id,
    'Name': s.name,
    'Type': s.type,
    'Role / Designation': s.role,
    'Department': s.department,
    'Email': s.email,
    'Phone': s.phone,
    'Status': s.status,
    'Joining Date': s.joiningDate,
    'Hours Logged (Month)': s.hoursLoggedThisMonth,
    'Skills': s.skills.join(', '),
    'Assigned Projects': s.assignedProjects.join(', ')
  }));
  const wsStaff = XLSX.utils.json_to_sheet(staffData);
  setColumnWidths(wsStaff, staffData);
  XLSX.utils.book_append_sheet(wb, wsStaff, 'Staff & Volunteers');

  // Sheet 5: Donations
  const donationsData = data.donations.map(d => ({
    'Donation ID': d.id,
    'Receipt #': d.receiptNumber,
    'Donor Name': d.donorName,
    'Donor Type': d.donorType,
    'Amount (₹)': d.amount,
    'Date': d.date,
    'Payment Method': d.paymentMethod,
    'Purpose': d.purpose,
    'Project Allocation': d.projectAllocation,
    'Tax Exemption Issued': d.taxExemptionIssued ? 'Yes (80G/12A)' : 'No',
    'Status': d.status
  }));
  // Append total row
  donationsData.push({
    'Donation ID': 'TOTAL',
    'Receipt #': '-',
    'Donor Name': 'TOTAL VERIFIED DONATIONS',
    'Donor Type': '-',
    'Amount (₹)': totalDonations,
    'Date': '-',
    'Payment Method': '-',
    'Purpose': '-',
    'Project Allocation': '-',
    'Tax Exemption Issued': '-',
    'Status': '-'
  });
  const wsDonations = XLSX.utils.json_to_sheet(donationsData);
  setColumnWidths(wsDonations, donationsData);
  XLSX.utils.book_append_sheet(wb, wsDonations, 'Donations');

  // Sheet 6: Expenses
  const expensesData = data.expenses.map(e => ({
    'Expense ID': e.id,
    'Project': e.project,
    'Category': e.category,
    'Amount (₹)': e.amount,
    'Date': e.date,
    'Vendor': e.vendor,
    'Payment Method': e.paymentMethod,
    'Description': e.description,
    'Status': e.status,
    'Approved By': e.approvedBy || 'Pending',
    'Receipt Ref': e.receiptRef
  }));
  expensesData.push({
    'Expense ID': 'TOTAL',
    'Project': '-',
    'Category': '-',
    'Amount (₹)': totalExpenses,
    'Date': '-',
    'Vendor': 'TOTAL APPROVED EXPENSES',
    'Payment Method': '-',
    'Description': '-',
    'Status': '-',
    'Approved By': '-',
    'Receipt Ref': '-'
  });
  const wsExpenses = XLSX.utils.json_to_sheet(expensesData);
  setColumnWidths(wsExpenses, expensesData);
  XLSX.utils.book_append_sheet(wb, wsExpenses, 'Expenses');

  // Sheet 7: Events
  const eventsData = data.events.map(ev => ({
    'Event ID': ev.id,
    'Title': ev.title,
    'Type': ev.type,
    'Associated Project': ev.project,
    'Date': ev.date,
    'Location': ev.location,
    'Organizer': ev.organizer,
    'Participants': ev.participantsCount,
    'Beneficiaries Reached': ev.beneficiariesReached,
    'Budget (₹)': ev.budget,
    'Spent (₹)': ev.spent,
    'Status': ev.status,
    'Outcomes': ev.outcomeSummary
  }));
  const wsEvents = XLSX.utils.json_to_sheet(eventsData);
  setColumnWidths(wsEvents, eventsData);
  XLSX.utils.book_append_sheet(wb, wsEvents, 'Events');

  // Sheet 8: Inventory
  const totalValuation = data.inventory.reduce((sum, i) => sum + (i.quantity * i.unitCost), 0);
  const inventoryData = data.inventory.map(i => ({
    'Item ID': i.id,
    'Item Name': i.itemName,
    'Category': i.category,
    'Quantity': i.quantity,
    'Unit': i.unit,
    'Unit Cost (₹)': i.unitCost,
    'Total Valuation (₹)': i.quantity * i.unitCost,
    'Location': i.location,
    'Reorder Threshold': i.reorderLevel,
    'Status': i.status,
    'Supplier': i.supplier
  }));
  inventoryData.push({
    'Item ID': 'TOTAL',
    'Item Name': 'TOTAL INVENTORY VALUATION',
    'Category': '-',
    'Quantity': 0,
    'Unit': '-',
    'Unit Cost (₹)': 0,
    'Total Valuation (₹)': totalValuation,
    'Location': '-',
    'Reorder Threshold': 0,
    'Status': '-',
    'Supplier': '-'
  });
  const wsInventory = XLSX.utils.json_to_sheet(inventoryData);
  setColumnWidths(wsInventory, inventoryData);
  XLSX.utils.book_append_sheet(wb, wsInventory, 'Inventory');

  // Sheet 9: Tasks
  const tasksData = data.tasks.map(t => ({
    'Task ID': t.id,
    'Title': t.title,
    'Project': t.project,
    'Assignee': t.assignee,
    'Priority': t.priority,
    'Status': t.status,
    'Due Date': t.dueDate,
    'Estimated Hours': t.estimatedHours,
    'Description': t.description
  }));
  const wsTasks = XLSX.utils.json_to_sheet(tasksData);
  setColumnWidths(wsTasks, tasksData);
  XLSX.utils.book_append_sheet(wb, wsTasks, 'Tasks');

  const fileName = `NGO_Consolidated_Master_Operations_${new Date().toISOString().split('T')[0]}.xlsx`;
  XLSX.writeFile(wb, fileName);
}

// 2. Individual Module Exports
export function exportModuleExcel(moduleName: string, items: any[], customFilename?: string) {
  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.json_to_sheet(items);
  setColumnWidths(ws, items);
  XLSX.utils.book_append_sheet(wb, ws, moduleName.slice(0, 31));
  const filename = customFilename || `NGO_${moduleName.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.xlsx`;
  XLSX.writeFile(wb, filename);
}

