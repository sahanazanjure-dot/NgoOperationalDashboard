// 4. Download Import Error Report
export function downloadErrorReport(moduleName: string, errors: { row: number; error: string; data?: any }[]) {
  const wb = XLSX.utils.book_new();
  const errorRows = errors.map(e => ({
    'Row #': e.row,
    'Validation Issue': e.error,
    'Raw Data Provided': JSON.stringify(e.data || {})
  }));
  const ws = XLSX.utils.json_to_sheet(errorRows);
  setColumnWidths(ws, errorRows);
  XLSX.utils.book_append_sheet(wb, ws, 'Import Errors');
  XLSX.writeFile(wb, `Import_Errors_${moduleName.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.xlsx`);
}
